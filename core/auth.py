"""Кто вошёл и что ему можно. Пока — заглушка, настоящий вход появится на этапе 5.

До LDAP сайт не знает, кто перед ним, но код уже сейчас должен спрашивать
роль в одном месте, а не решать сам. Поэтому правило такое: всё, что видно
только админу (плашка публикации, страница ввода плана, настройки),
проверяется через is_admin() отсюда — и нигде больше.

На этапе 5 меняется только этот файл: current_user() начнёт возвращать
доменную учётку, current_role() — роль из групп AD. Страницы не трогаются.

`!!` **Проверка в `layout()` защищает ЭКРАН, а не действие.** Спрятать
страницу мало: коллбэк Dash — это обычный POST на `/_dash-update-component`,
и его можно позвать напрямую, минуя разметку. Поэтому каждый коллбэк,
который ЧТО-ТО МЕНЯЕТ, закрывается `@admin_only` (см. ниже) — отдельно
от того, показали мы кнопку или нет. Найдено внешним аудитом 18.08.2026
и проверено в коде: у страниц плана и виджетов проверка стояла только
в `layout()`.
"""

import functools
import getpass
import logging

from dash.exceptions import PreventUpdate

log = logging.getLogger(__name__)

# Роли проекта. Ровно две — по ROADMAP: ~70 зрителей и 2 админа визуала.
VIEWER = "viewer"
ADMIN = "admin"


def current_user() -> str:
    """Имя того, кто работает с сайтом.

    Заглушка берёт имя пользователя операционной системы — в разработке это
    честнее выдуманной строки: в черновиках плана видно, кто их писал.
    """
    return getpass.getuser()


def current_role() -> str:
    """Роль текущего пользователя.

    Заглушка: в разработке все — админы, иначе форму ввода плана было бы
    не открыть до этапа 5. Боевой код будет смотреть в группы AD.
    """
    return ADMIN


def is_admin() -> bool:
    return current_role() == ADMIN


def admin_only(fn):
    """Сторож изменяющего коллбэка: не админ — коллбэк не выполняется.

    Вешается ПОД `@callback`, то есть ближе к функции::

        @callback(Output(...), Input(...))
        @auth.admin_only
        def change_structure(...):

    Порядок обязателен: Dash должен зарегистрировать сторожа, а не голую
    функцию, иначе проверка окажется внутри того, что уже вызвали.

    `!!` Отказ — это `PreventUpdate`, а НЕ «вернуть no_update по числу
    выходов». Разница принципиальная: выходов у коллбэков от одного до
    четырёх, и сторожу пришлось бы знать их число — то есть держать рядом
    с `@callback` второе такое же число и следить, чтобы они не разошлись.
    Проект уже обжигался на паре чисел, обязанных совпадать (margin
    и сдвиг подписей СЭЭ). `PreventUpdate` — штатный способ Dash оборвать
    коллбэк, и он не зависит от числа выходов вовсе.

    `!!` Отказ ПИШЕТСЯ В ЛОГ. Молчаливый отказ на сервере неотличим от
    поломки: и там и там на экране ничего не происходит. В журнале должно
    остаться, кто и куда стучался.

    Что сторож НЕ делает: не показывает человеку сообщение. Показать
    его через `PreventUpdate` нельзя, а тому, кто пришёл в обход
    интерфейса, объяснение и не нужно. Там, где отказ должен быть виден
    (страница «Настройки»), проверка стоит внутри тела и возвращает
    плашку — см. `pages/settings.py`, `apply_settings`.
    """
    @functools.wraps(fn)
    def guard(*args, **kwargs):
        if not is_admin():
            log.warning("отказано в действии: пользователь %s (роль %s) "
                        "вызвал коллбэк %s", current_user(), current_role(),
                        fn.__name__)
            raise PreventUpdate
        return fn(*args, **kwargs)
    return guard
