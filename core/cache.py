"""Общий кэш приложения (flask-caching, хранение на диске).

Вынесен в отдельный модуль, а не создан в app.py: страницы и core/data.py
импортируются раньше, чем app.py дочитан до конца, и тянуть кэш оттуда
означало бы циклический импорт.

Кэш привязывается дважды, и обе привязки нужны:

- к запасному Flask-приложению здесь — тогда memoize работает и без
  сайта: из python-консоли и из тестов;
- к настоящему приложению сайта в app.py (`cache.init_app(server)`) —
  внутри веб-запроса flask-caching ищет кэш именно у текущего
  приложения, и без этой привязки МОЛЧА работает без кэша.

**Тип кэша — FileSystemCache, и это осознанно под этап 5.** На сервере сайт
идёт под Gunicorn в несколько процессов-воркеров. SimpleCache живёт в памяти
ОДНОГО процесса — тогда каждый воркер грел бы свой кэш отдельно, дублируя
чтения с диска. FileSystemCache кладёт кэш в общую папку, и все воркеры
делят его. Рассинхрона данных при этом не будет: ключ у конфига — время
правки файла, у фактов — номер опубликованной версии; ключи детерминированы,
у всех воркеров совпадают, поэтому «общий» здесь безопасно.

Redis не берём намеренно: это ещё один сервис, который админам ставить,
держать и охранять. Для ~70 читателей и редких записей файлового кэша хватает.
Если однажды упрёмся — сменить CACHE_TYPE на RedisCache, код вызовов не тронется.

Значения кэша (DataFrame фактов, dict конфига) сериализуются на диск через
pickle. Замер 11.08.2026 на 157 102 строках: собрать таблицу заново стоит
476 мс (292 мс чтение DuckDB + 184 мс перевод разрезов в категории), взять
из кэша — 13 мс. Ради этих 460 мс на каждый запрос кэш и держится.

`!!` **Кэш ограничен и чистится — это не «поставили и забыли».** Записей
столько же, сколько было версий данных: каждый прогон ETL заводит новую,
а старую никто не удаляет. К 11.08.2026 так набралось 2,25 ГБ в 438 файлах,
причём самые толстые (до 88 МБ) остались от времён, когда разрезы хранились
строками. Ограничителей теперь два, и они разные по смыслу: порог считает
файлы, `sweep()` — байты.
"""

import logging
import os
from pathlib import Path

from flask import Flask
from flask_caching import Cache

log = logging.getLogger(__name__)

# Папка кэша — отдельная от боевого хранилища. data/ и так в .gitignore.
# !! Бэкап (этап 5) снимать с data/analytics.duckdb, а НЕ с этой папки:
# кэш восстановимый мусор, его потеря ничем не грозит — при следующем
# запросе он наполнится сам. Переопределяется переменной окружения на
# случай, если админы захотят вынести кэш на быстрый диск (tmpfs).
CACHE_DIR = os.getenv("DASHBOARD_CACHE_DIR", str(Path("data") / "cache"))

# Порог — предохранитель библиотеки: как только файлов становится больше,
# она сама выбрасывает сперва просроченные, потом самые старые.
#
# !! Порог считает ФАЙЛЫ, а не байты, и одного его мало (см. `sweep` ниже).
# Умолчание библиотеки — 500, и оно нам не годилось: 11.08.2026 в папке
# лежало 438 файлов на 2,25 ГБ, самые старые — восемнадцатидневные.
# Чистка не запускалась ни разу, потому что до порога не доходило.
CACHE_THRESHOLD = int(os.getenv("DASHBOARD_CACHE_THRESHOLD", "60"))

# Потолок по объёму, мегабайты. Одна запись фактов сегодня — 6,6 МБ
# (замерено), значит 150 МБ это больше двадцати записей: с запасом
# на несколько версий подряд и на пару воркеров, но без гигабайтов.
# Умеренно намеренно — вырастут данные, вернёмся и поднимем.
CACHE_LIMIT_MB = int(os.getenv("DASHBOARD_CACHE_LIMIT_MB", "150"))

# Таймаут: запись со старой версией в ключе становится негодной через
# 10 минут. !! Сама по себе она с диска НЕ исчезает — таймаут решает,
# отдавать ли её, а место освобождают порог и `sweep`.
cache = Cache(config={
    "CACHE_TYPE": "FileSystemCache",
    "CACHE_DIR": CACHE_DIR,
    "CACHE_DEFAULT_TIMEOUT": 600,
    "CACHE_THRESHOLD": CACHE_THRESHOLD,
})
cache.init_app(Flask("damu-cache"))

#: Служебные файлы самой библиотеки (счётчик записей). Их не трогаем:
#: без счётчика библиотека считает, что кэш пуст, и порог перестаёт работать.
_HOUSEKEEPING = ("__wz_cache_count",)


def sweep(limit_mb: int | None = None) -> tuple[int, float]:
    """Удаляет самые старые записи, пока папка не влезет в лимит.

    Зачем нужен вдобавок к порогу: порог считает файлы, а болит от байтов.
    Одна запись фактов весит то 5 МБ, то 88 (столько занимали записи
    до 07.08.2026, когда разрезы хранились строками, а не категориями).
    Сорок файлов по 88 МБ — это 3,5 ГБ при формально соблюдённом пороге.

    !! Удалять записи кэша БЕЗОПАСНО в любой момент. Кэш целиком выводится
    из `data/analytics.duckdb`: пропала запись — следующий запрос соберёт
    её заново (замерено 11.08.2026: 476 мс против 13 мс из кэша) и положит
    обратно. Ни одна цифра при этом не меняется — у каждой версии данных
    свой ключ, старая копия к новым данным подставиться не может.

    Порядок удаления — по времени правки, самые старые первыми: свежие
    записи это и есть текущая версия данных, их трогаем в последнюю очередь.

    Возвращает (сколько удалено, сколько мегабайт осталось).
    """
    limit = (limit_mb if limit_mb is not None else CACHE_LIMIT_MB) * 1024 * 1024
    folder = Path(CACHE_DIR)
    if not folder.is_dir():
        return 0, 0.0

    files = []
    for item in folder.iterdir():
        if not item.is_file() or item.name in _HOUSEKEEPING:
            continue
        try:
            stat = item.stat()
        except OSError:                     # исчез между обходом и замером
            continue
        files.append((stat.st_mtime, stat.st_size, item))

    total = sum(size for _, size, _ in files)
    if total <= limit:
        return 0, total / 1024 / 1024

    removed = 0
    for _, size, item in sorted(files):     # старые первыми
        if total <= limit:
            break
        try:
            item.unlink()
        except OSError:                     # занят другим процессом — пропускаем
            continue
        total -= size
        removed += 1

    log.info("кэш: удалено %d записей, осталось %.0f МБ (лимит %d МБ)",
             removed, total / 1024 / 1024, limit // 1024 // 1024)
    return removed, total / 1024 / 1024
