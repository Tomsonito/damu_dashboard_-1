"""Страницы админа под одной шапкой: общая полоса вкладок.

В шапке сайта у админа один пункт — «Настройки». За ним три страницы:
ввод плана, набор виджетов и оформление. Раньше они были тремя отдельными
пунктами выпадающего меню, и человек не видел, что это одно место.

**Вкладки — это ссылки на настоящие страницы, а не переключатель внутри
одной.** Так каждая сохраняет свой адрес (его можно дать коллеге), у каждой
остаются свои коллбэки, и переход между ними ничего не ломает. Внешне это
всё равно вкладки: та же полоса, та же подсветка активной, что и в разделах.

Список живёт здесь, а не в каждой странице: иначе, добавив четвёртую,
пришлось бы вспомнить про три файла и в одном обязательно забыть.
"""

from dash import html

#: Страницы админа в порядке вкладок. Порядок задал пользователь:
#: сначала ввод плана, потом виджеты, потом оформление.
PAGES = (
    ("/plan", "Ввод плана"),
    ("/widgets", "Виджеты"),
    ("/settings", "Оформление"),
)


def tabs(active: str) -> html.Div:
    """Полоса вкладок настроек. `active` — адрес текущей страницы.

    Классы те же, что у вкладок раздела (`damu-sec-*`): одинаковые на вид
    элементы должны быть одинаковыми и в стилях, иначе они разъедутся при
    первой же правке CSS.
    """
    return html.Div(
        html.Div(
            [
                html.A(
                    title,
                    href=href,
                    className="damu-sec-tab" + (" active" if href == active else ""),
                )
                for href, title in PAGES
            ],
            className="damu-sec-tabs",
        ),
        className="damu-admin-tabs",
    )


def page_header(active: str, title: str, hint: str = "") -> list:
    """Заголовок страницы админа: полоса вкладок, название, подпись под ним."""
    parts = [tabs(active), html.H2(title, className="mt-3")]
    if hint:
        parts.append(html.P(hint, className="text-muted small"))
    return parts
