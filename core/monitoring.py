"""Отправка ошибок в Sentry — пока только для `etl/run.py`.

**Подключено только к ETL, не к сайту** (решено с пользователем 11.08.2026).
Сайт сейчас поднимают на пять минут во внутренней сети для проверок — там
Sentry не даст пользы, зато каждая проверка из этой сессии улетала бы
в кабинет как «продакшн-ошибка». ETL другое дело: он уже сейчас работает
без присмотра (`python -m etl.run`, а на этапе 5 — cron каждые 5 минут)
и пишет ошибку в `data/etl.log`, который никто не читает, пока сам туда
не заглянет. Sentry закрывает этот разрыв — узнаём о падении сами,
с полным стектрейсом, в момент, когда оно случилось.

К сайту возвращаемся на этапе 5, когда он станет жить постоянно
(см. ROADMAP, «Что ждёт решения человека»).

**Включается переменной окружения, а не всегда.** `DASHBOARD_DEBUG`
в проекте по тому же правилу — опасное или шумное поведение не должно
включаться само по факту наличия пакета в `requirements.txt`.
"""

import logging
import os

log = logging.getLogger(__name__)

#: DSN — адрес проекта в Sentry, не секрет уровня пароля (это ключ ЗАПИСИ
#: событий, а не чтения), но в код всё равно не вписываем — тем же приёмом,
#: что и DATABASE_URL: смена проекта Sentry не должна требовать правки кода.
SENTRY_DSN = os.getenv("SENTRY_DSN", "")


def init_etl() -> bool:
    """Включает отправку ошибок ETL в Sentry, если задан SENTRY_DSN.

    Без переменной — тихо ничего не делает: локальная разработка и работа
    без Sentry остаются рабочими сценариями, а не требуют настройки.

    Возвращает True, если отправка включена — `etl/run.py` пишет это в лог,
    чтобы при чтении `data/etl.log` было видно, дублируется ли ошибка
    в Sentry или нет.
    """
    if not SENTRY_DSN:
        return False
    import sentry_sdk

    sentry_sdk.init(
        dsn=SENTRY_DSN,
        # !! traces_sample_rate НЕ задан. Это включило бы трассировку
        # производительности (APM) — она платная по объёму и тут не нужна:
        # прогон и так пишет свою длительность в лог. Нужны только ошибки.
        environment=os.getenv("DASHBOARD_ENV", "development"),
    )
    return True
