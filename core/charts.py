    bottom = float(df["shown"].min() or 0)
    hi = top * 1.22 if top > 0 else (1.0 if bottom >= 0 else 0.0)
    lo = bottom * 1.22 if bottom < 0 else 0.0
    fig.update_xaxes(visible=False, range=[lo, hi])
    # `automargin` сам отводит место под подписи, какой бы длины они ни
    # вышли после сокращения: у разных разрезов подписи разной длины.
    # !! Поля здесь не задаём: `build()` ставит свои уже после этой функции,
    # и всё, что мы напишем в `margin`, будет затёрто. Автополя оси
    # переживают это — они прибавляются к заданным, а не заменяют их
    #
    # !! «category descending», а не «ascending» — для алфавитного порядка.
    # У «total ascending» самое крупное значение оказывается СВЕРХУ (текущее
    # поведение, проверено на экране), а не потому что ascending значит
    # «сверху». Категория с конца списка рисуется сверху в обоих случаях,
    # поэтому для «А сверху, дальше вниз» список нужен по убыванию.
    # Не проверено глазами (правило 3 — сайт запускался с разрешения,
    # но не после этой конкретной правки).
    order = "category descending" if sort == "alpha" else "total ascending"
    fig.update_yaxes(categoryorder=order, showgrid=False,
                     automargin=True, ticksuffix="  ", **CATEGORY_TICKS)
    fig.update_layout(bargap=0.34)
    # Подписи столбиком от одного края — просьба пользователя 11.08.2026,
    # только для СЭЭ. У остальных разделов подписи прежние, правого края.
