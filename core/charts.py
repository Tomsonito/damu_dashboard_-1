# Реестр заполняется декоратором при импорте модуля
_REGISTRY: dict[str, dict] = {}

#: Сколько знаков заголовка помещается в одну строку НА КОЛОНКУ сетки.
#: Замер 11.08.2026: средний виджет (6 колонок из 12) на экране 1024 —
#: 336 px, шрифт заголовка 17 px, то есть ~9,4 px на знак и ~36 знаков.
#: Отсюда 6 знаков на колонку; на большом виджете (12 колонок) выходит 72,
#: и это сходится с замером — 705 px, ~75 знаков.
#:
#: !! Оценка приблизительная намеренно. Точную ширину знает только браузер,
#: а заголовок собирает сервер: он не видит ни размера окна, ни шрифта,
#: который выбрал админ. Ошибка на знак-два ничего не стоит — цена вопроса
#: одна лишняя строка заголовка, а не обрезанный текст.
#: Размер шрифта внутри диаграмм — подписи категорий, числа у полос, оси.
#:
#: !! Не меньше 16 px (11.08.2026, просьба пользователя: «сейчас глаза
#: болят»). Было 11. Число это не косметика, а решение с последствиями:
#: при 16 px подписи требуют около 20 px на строку, поэтому двадцать
#: областей просят ~500 px высоты, и диаграммы с разрезом по областям
#: встали во всю ширину по одной в ряд. Сетка 2×2 на одном экране при таком
#: шрифте невозможна — выбор сделан пользователем в пользу читаемости.
CHART_FONT_PX = 16

#: Заголовок — чуть крупнее содержимого, но без перебора: он занимает
#: верхнее поле, а высота нужна самим данным.
TITLE_FONT_PX = 17

#: Подмена пробела на время переноса заголовка. `textwrap` рвёт строку
#: по любому пробельному символу, включая неразрывный (`\xa0` подходит
#: под `\s` в Unicode-режиме `re`, проверено) — поэтому нужен символ,
#: который вообще не пробельный. `\x00` в тексте заголовка встретиться
#: не может, и после переноса он заменяется обратно на обычный пробел.
GLUE = "\x00"

#: Знаков заголовка на колонку сетки. Пересчитано под 17 px: около 9,4 px
#: на знак (замер 11.08.2026), колонка сетки ~56 px на экране 1024.
TITLE_CHARS_PER_COLUMN = 5.8

#: Ширина виджета по умолчанию — вся сетка. Так его строят «Разбор»
#: и главная: у них график один на экран, пресета размера нет.
TITLE_FULL_COLUMNS = 12

#: Больше трёх строк заголовок не занимает: дальше он съедает сам график.
#: Хвост при этом теряется — но теряется у САМЫХ длинных названий и только
#: в самом узком виджете, а до 11.08.2026 там обрезалась даже первая строка.
TITLE_MAX_LINES = 3

#: Поля сверху под заголовок: базовые плюс по строке. Однострочному хватало
#: 60 px и раньше; многострочный без добавки наезжал бы на область графика.
TITLE_LINE_H = 25
TITLE_MARGIN_BASE = 40

#: Запасные цвета для рядов после первого. Первым идёт цвет темы —
#: у большинства наших видов ряд всего один, и он окрашивается им.
_PALETTE_TAIL = px.colors.qualitative.Plotly[1:]


@dataclass
class Ctx:
    """Всё, что диаграмма может попросить: что показывать и в каком масштабе."""

    indicator: str
    year: int
    regions: list[str] | None
    log: bool = False
    #: Раздел (колонка `program`). None — считать по всем разделам сразу:
    #: так смотрят главная и «Разбор». Страница раздела передаёт свой.
    program: str | None = None
    #: Год, выбранный человеком в шапке. Совпадает с `year`, пока у показателя
    #: есть данные за него; разошлись — `year` подставлен слоем данных,
    #: и заголовок обязан про это сказать (см. `title`).
    asked_year: int | None = None
    #: Свёрнутый показ вида «Годы»: сколько последних лет видно сразу,
    #: остальные раскрывает кнопка на странице. `None` — показывать все
    #: года, как было раньше. Читает только `_years_total`, остальные
    #: 24 вида это поле не видят.
    recent_years: int | None = None
    #: Ширина виджета в колонках сетки (4 / 6 / 12) — из пресета размера.
    #: Нужна только заголовку: по ней он решает, поместится ли строка
    #: целиком или год пора переносить. `None` — виджет во всю ширину.
    columns: int | None = None
    #: Разрез вида — «по банкам», «по отраслям (ОКЭД)» и подобное. Кладёт
    #: его `build()` из реестра, а не страница: разрез — свойство вида,
    #: и вид знает его сам. Пусто — вид не режет данные (итог, шкала)
    #: или пишет заголовок сам (месяцы, сравнение лет).
    cut: str = ""
    #: Явно переданная помесячная серия. Нужна только тестовому СЭЭ 2:
    #: исходная выгрузка СЭЭ помесячных строк пока не содержит.
    monthly: pd.DataFrame | None = None
    #: Пометка не даёт тестовой разбивке выглядеть как данные источника.
    monthly_is_test: bool = False
    #: Компактная динамика СЭЭ 2: подписи над столбцами и чистая ось.
    compact_years: bool = False

    @property
    def meta(self) -> dict:
        return data.get_indicator_meta(self.indicator)

    @property
    def unit(self) -> str:
        return self.meta["display_unit"] or self.meta["unit"]

    @property
    def title_parts(self) -> tuple[str, str]:
        import re
        head = self.meta["title"]
        annotation = ""
        
        m = re.search(r'\((.*?)\)', head)
        if m:
            annotation = m.group(1)
            head = re.sub(r'\s*\(.*?\)', '', head)
                
        if self.cut:
            head += f" {self.cut}"
        return head, annotation

    @property
    def title(self) -> str:
        # !! Разрез в заголовке обязателен, когда на одной вкладке лежат
        # несколько видов одного показателя. У Өрлеу так и было: четыре
        # диаграммы подряд назывались «Выдано кредитов — 2026 год», и чем
        # они отличаются, приходилось угадывать по картинке (замечено
        # пользователем 11.08.2026). Слово берётся из реестра диаграмм —
        # там, где вид объявлен, а не переписывается в config.yaml: реестр
        # уже знает, по какой колонке режет, и дублировать это словами
        # значило бы завести второй источник правды.
        head, _ = self.title_parts
        # !! Единица измерения — ЗДЕСЬ, в скобках после названия, и больше
        # нигде (17.08.2026, просьба пользователя). Раньше её носила каждая
        # подпись столбца, то есть повторяла себя столько раз, сколько
        # на диаграмме полос. Одно название — одна единица.
        #
        # Место выбрано не случайно: единица — часть ответа на вопрос
        # «что за число», а этот вопрос задают, читая заголовок. Отдельная
        # надпись в углу (так было до 11.08.2026 у не-СЭЭ) отвечала на него
        # в стороне от вопроса, и её приходилось искать глазами.
        #
        unit = f"({self.unit})" if self.unit else ""
        # !! СЭЭ — короткие заголовки без года (11.08.2026, просьба
        # пользователя): «Сохранено раб. мест по регионам» вместо
        # «Количество сохраненных рабочих мест по регионам — 2024 год ·
        # за 2026 данных нет». Короткое имя берётся из того же поля
        # `short`, что и подпись карточки-показателя — второго названия
        # заводить не пришлось. Обычный совпавший год здесь не повторяется:
        # его уже видно в глобальном фильтре. Но подставленный год теперь
        # обязан появиться прямо в заголовке и у СЭЭ: после возврата видимых
        # фильтров надпись «2026» рядом с графиком за 2024-й иначе стала бы
        # прямым противоречием. Ограничено программой, а не индикатором,
        # чтобы правило не разошлось при появлении новых показателей СЭЭ.
        if self.program == "СЭЭ":
            # !! Фолбэк — `meta["title"]` СЫРЬЁМ, не `head`: тот уже несёт
            # приклеенный `cut` (см. `title_parts` выше), и наклеить его
            # второй раз значило бы получить «по регионам по регионам».
            short = self.meta.get("short") or self.meta["title"]
            head = f"{short} {self.cut}".strip() if self.cut else short
            tail = ""
            if self.asked_year and self.asked_year != self.year:
                tail = f"{self.year} · последние доступные данные"
        else:
            tail = f"{self.year} год"
            if self.asked_year and self.asked_year != self.year:
                # !! Пометка обязательна. Тихо подставить 2024-й там, где
                # человек выбрал 2026-й, — худший вид ошибки: цифры выглядят
                # свежими, график не пустой, и заметить подмену нечем
                tail += f" · за {self.asked_year} данных нет"
        # !! Длинный заголовок переносится, а не обрезается. Разрез добавил
        # к строке 15–20 знаков, и в среднем виджете (336 px на экране
        # 1024) она перестала помещаться: «Выдано кредитов по субъектности
        # — 2026 год» это 385 px против 336 — хвост уезжал за край молча,
        # без всякой ошибки. Замерено в браузере 11.08.2026; перенос года
        # на вторую строку даёт 291 px и запас 28.
        budget = int((self.columns or TITLE_FULL_COLUMNS) * TITLE_CHARS_PER_COLUMN)
        named = f"{head} {unit}" if unit else head
        whole = f"{named} — {tail}" if tail else named
        if len(whole) <= budget:
            return whole
        # Переносим по словам, а не только перед годом: у СЭЭ названия
        # показателей длинные («Налоговые поступления (в сумме, млрд
        # тенге)»), и одной точки разрыва не хватает — первая строка сама
        # не помещалась. Это не регрессия от разреза: до него заголовок
        # был не короче и обрезался ровно так же, просто молча
        # (замерено 11.08.2026: 501 px текста в виджете 335 px).
        #
        # Год переносится ЦЕЛИКОМ, отдельной строкой. Перенос всей строки
        # разом рвал его пополам («Выдано кредитов — 2026 / год»), а год —
        # то, ради чего заголовок и читают вторым делом.
        # !! Единица «(млрд ₸)» едет в перенос ОДНИМ словом, и это не мелочь.
        # Два подхода до этого не сработали:
        #
        #   1. приписать к последней строке ПОСЛЕ переноса — строка вылезала
        #      за бюджет: «по отраслям (ОКЭД) (млрд ₸)» это 27 знаков против
        #      23 на узком виджете (поймал `tests/test_chart_titles.py`);
        #   2. отдать `textwrap` как есть — он рвёт по пробелам, и пробел
        #      внутри скобок для него такой же: «(млрд / ₸)».
        #
        # Поэтому внутренний пробел на время переноса подменяется символом,
        # по которому `textwrap` не рвёт, а после переноса возвращается
        # обратно. Пробел ПЕРЕД скобкой остаётся настоящим: единице можно
        # уехать на свою строку целиком, нельзя только разорваться пополам.
        glued = f"{head} {unit.replace(' ', GLUE)}" if unit else head
        head_lines = textwrap.wrap(glued, width=budget,
                                   break_long_words=False) or [glued]
        head_lines = [line.replace(GLUE, " ") for line in head_lines]
        # !! Перенос теперь общий для ВСЕХ разделов, включая СЭЭ. До
        # 17.08.2026 ветка СЭЭ возвращала строку выше, не заходя сюда, —
        # её заголовки просто не переносились. Пока в них не было единицы,
        # это сходило с рук: «Выпуск продукции по регионам» это 28 знаков
        # при бюджете 34. С «(млрд ₸)» стало 37, и хвост начал уезжать
        # за край МОЛЧА, без ошибки и без обрезки — Plotly рисует, что
        # влезло. Поймано замером сразу после правки; лечится тем, что
        # у СЭЭ просто пустой `tail`, а перенос один на всех.
        if not tail:
            return "<br>".join(head_lines[:TITLE_MAX_LINES])
        tail_lines = textwrap.wrap(tail, width=budget,
                                   break_long_words=False) or [tail]
        keep = max(1, TITLE_MAX_LINES - len(tail_lines))
        return "<br>".join(head_lines[:keep] + tail_lines)

    def scaled(self, df: pd.DataFrame, column: str = "value") -> pd.DataFrame:
        """Готовит колонки для показа.

        `shown` — значение в масштабе показа (для осей и размеров).
        `текст`  — то же значение строкой с разрядами, БЕЗ единицы.

        !! Единицы в подписи столбца нет с 17.08.2026 (просьба пользователя).
        Была: «12 929 млрд ₸» на каждом из пяти столбцов. У «Динамики
        по годам» подпись стоит ВНУТРИ столбца и разворачивается вертикально,
        поэтому «млрд ₸» съедало больше высоты, чем само число, — и повторяло
        одно и то же пять раз подряд. Теперь единица названа один раз,
        в заголовке диаграммы: «Выпуск продукции (млрд ₸)» (см. `title`).
        """
        out = df.copy()
        out["shown"] = out[column] / self.meta["divisor"]
        out["текст"] = [data.format_value(v, self.indicator, with_unit=False)
                        for v in out[column]]
        return out


def chart(value: str, label: str, log_ok: bool = False, cut: str = ""):
    """Регистрирует функцию как вид диаграммы.

    log_ok=True — вид умеет логарифмическую шкалу. Отмечен он только там,
    где логарифм честен: на точках, ящиках и подобном. На столбцах и площадях
    логарифм врёт, потому что длина столбца обязана быть пропорциональна
    значению и отсчитываться от нуля.

    cut — разрез словами («по банкам»), он попадает в заголовок диаграммы
    через `Ctx.title`. Пусто у видов, которые ничего не режут (итог по
    стране, шкала) и у тех, что пишут заголовок сами (месяцы, сравнение
    лет): там разрез назван прямо в их строке заголовка.
    """

    def register(fn):
        _REGISTRY[value] = {"label": label, "builder": fn, "log_ok": log_ok,
                            "cut": cut}
        return fn

    return register


def get_choices() -> list[dict]:
    """Список видов для переключателя в интерфейсе."""
    return [{"label": item["label"], "value": key} for key, item in _REGISTRY.items()]


def supports_log(chart_type: str) -> bool:
    entry = _REGISTRY.get(chart_type)
    return bool(entry and entry["log_ok"])


#: Цвета, одинаково читаемые и на светлом, и на тёмном фоне.
#:
#: !! Диаграммы собираются на СЕРВЕРЕ, а тему человек выбирает в браузере
#: (localStorage) — сервер о ней не знает. Значит фигура должна выглядеть
#: прилично при обеих. Отсюда полупрозрачный серый вместо чёрного текста
#: и вместо светлой сетки: контраст чуть ниже предельного, зато не бывает
#: чёрного по чёрному. Захотим полный контраст — придётся протащить тему
#: в каждый коллбэк, который строит диаграмму.
NEUTRAL_INK = "rgba(128,124,122,1)"
NEUTRAL_GRID = "rgba(128,124,122,0.25)"

#: Сетка пунктиром, а не сплошной (просьба пользователя 07.08.2026).
#: `dot` — точками; `dash` штрихами читается тяжелее и на графике
#: с полосами начинает походить на отметку порога, а не на разметку.
GRID_DASH = "dot"

#: Пунктирная линия прозрачнее сплошной при той же заливке: половина её
#: длины — пустота (замерено: штрих 3 px, пропуск 3 px). Поэтому у сетки
#: своя прозрачность, чуть выше общей `NEUTRAL_GRID` — чтобы на экране
#: она весила столько же, сколько весила сплошная. Нулевая линия остаётся
#: на `NEUTRAL_GRID`: она сплошная, и добавлять ей веса не нужно.
GRID_COLOR = "rgba(128,124,122,0.34)"


#: Ось категорий: подписывать КАЖДУЮ, не спрашивая Plotly.
#:
#: !! Это правка от одной и той же поломки, случившейся трижды (07.08.2026 —
#: банки Гар. выдачи, 11.08.2026 — регионы СЭЭ и ещё три раздела). В тесноте
#: Plotly не сжимает шрифт и не поворачивает текст, а **прячет часть
#: подписей**, чтобы оставшиеся не наложились. Ошибки нет ни в консоли,
#: ни в логе: график рисуется целиком, столбцы все на месте — врёт только
#: подпись. Пользователь каждый раз находил это глазами.
#:
#: `tickmode="linear"` + `dtick=1` на категориальной оси означает «подпись
#: у каждой категории». Решение принимаем мы, а не библиотека: пусть лучше
#: подписи встанут теснее, чем часть исчезнет молча.
#:
#: Шрифт 11 px вместо умолчания — чтобы при 15–17 px на строку подписи
#: стояли свободно. Столько места остаётся у четырёх диаграмм на одном
#: экране; в оригинальном портале, с которого срисован дашборд, ровно так
#: же — около 15 px на строку.
CATEGORY_TICKS = dict(tickmode="linear", dtick=1,
                      tickfont=dict(size=CHART_FONT_PX))

#: Подписи регионов/отраслей выровнены по ЛЕВОМУ краю, а не по правому
#: умолчанию Plotly (11.08.2026, СЭЭ). У Plotly нет параметра для смены
#: text-anchor подписей категориальной оси — единственный официальный путь
#: сделать это на сервере, без JS, это ЗАМЕНИТЬ подписи оси своими
#: annotations. См. `_left_align_categories`.
#:
#: `LEFT_ALIGN_PAD_PX` — отступ от левого края картинки в пикселях
#: (не в долях ширины: ширина фигуры на сервере не известна, growing
#: responsive-контейнер решает её в браузере). `xshift` в annotations
#: считается в пикселях независимо от системы координат — этим и берём.
#:
#: Он же — ВИДИМЫЙ зазор между концом самой длинной подписи и началом
#: полос: место под список отмеряется по оценке ширины (ниже), а всё,
#: что оценка не добрала, и остаётся этим просветом.
LEFT_ALIGN_PAD_PX = 10

#: Шрифт списка названий — МЕНЬШЕ общего `CHART_FONT_PX` (16), и это не
#: отступление от правила «не мельче 16», а отдельный случай, разобранный
#: отдельно (12.08.2026, СЭЭ «Регионы»/«Отрасли»). Замерено в браузере:
#: при 16 px бокс подписи — 22 px, а шаг между строками при 20 категориях
#: даже в увеличенном пресете (500 px, `medium_tall`) — 21 px. Не хватало
#: буквально пикселя, но хватало, чтобы подписи КАСАЛИСЬ друг друга.
#: Правило «минимум 16» — про то, что человек ЧИТАЕТ как значение (числа
#: у полос, заголовок); список из двадцати названий, где строки и так
#: идут подряд без пропуска, — не то место, где годится тот же порог.
LEFT_ALIGN_FONT_PX = 14

#: Ширина подписи оценивается по БУКВАМ, а не «знаков × среднее».
#:
#: Почему не одним коэффициентом. Кириллица непропорциональна: замер
#: в браузере тем же шрифтом (12.08.2026, `measureText` на 14 px Golos
#: Text) дал разброс от 7,4 px на знак у «A · Сельское, лесно…» до
#: 13,9 у строки из «Щ». Один коэффициент обязан покрывать худшее —
#: и тогда обычные названия получают его целиком в виде пустоты:
#: при 11,5 px/знак «Кызылординская» шириной 120 px резервировала 167,
#: то есть 45 px пустого места, а обрезанные названия отраслей — 70.
#: Занизить его тоже нельзя, это уже пробовали: при 8,0 px/знак
#: «Оптовая и рознич[ная]» заезжала на полосы на 60 px.
#:
#: Двух чисел хватает, потому что широкие буквы — это узкий список,
#: а не плавный ряд: между «ю» (10,9) и «ш» (11,3) проходит разрыв,
#: ниже него всё умещается в базовую ширину. Проверено на 25 реальных
#: названиях плюс строках из сплошных «Ш» и «Щ»: оценка нигде не ниже
#: настоящей ширины (худший запас — 1 px у «Щ»), а в среднем выше неё
#: на 7 px, и этот излишек как раз читается как ровный просвет.
#:
#: !! Пересчитывать эти числа при смене шрифта: они замерены на Golos
#: Text. Способ — `measureText` в браузере, шрифт диаграмм тот же, что
#: у страницы.
LEFT_ALIGN_PX_PER_CHAR = 8.8
LEFT_ALIGN_WIDE_BONUS_PX = 5.2
LEFT_ALIGN_WIDE_CHARS = frozenset("ЖМФШЩЫЮжшщWMwm")


def _left_align_reserve(categories: list) -> int:
    """Сколько пикселей нужно под самую ШИРОКУЮ подпись списка.

    Общая формула для двух мест, которым обязательно считать ОДНО И ТО ЖЕ
    число: `_left_align_categories` (куда сдвинуть подписи от края данных)
    и `build()` (какое поле слева выделить под них). Разъедутся эти два —
    подписи либо провалятся в пустоту, либо снова наедут на полосы
    (ровно так уже было один раз, см. `_left_align_categories`).

    !! Самая широкая — не то же самое, что самая длинная, и раньше здесь
    бралась именно длина в знаках. На регионах это расходится сразу:
    «Карагандинская» и «Кызылординская» — обе по 14 знаков, но вторая
    на 6 px шире. Считать надо ту, что займёт больше места, иначе
    ширину поля задаёт не тот, кто в него не влезет.
    """
    widest = 0.0
    for item in categories:
        width = sum(
            LEFT_ALIGN_PX_PER_CHAR
            + (LEFT_ALIGN_WIDE_BONUS_PX if ch in LEFT_ALIGN_WIDE_CHARS else 0)
            for ch in str(item)
        )
        widest = max(widest, width)
    return LEFT_ALIGN_PAD_PX + int(widest)


def _left_align_categories(fig: go.Figure) -> int:
    """Подписи оси Y — своими надписями от одного левого края, списком.

    !! Раньше (до 11.08.2026) то же самое делал скрипт в браузере:
    `MutationObserver` на весь документ плюс `getBBox()` в цикле по каждой
    подписи каждого графика на любое изменение DOM — цена была в секундах
    подвисания страницы (найдено и снято 11.08.2026, разбор в CODE_GUIDE).
    Здесь то же самое решается один раз при постройке фигуры на сервере:
    подписи оси прячутся, вместо них — обычные `annotations`.

    !! `xref="paper", x=0` — НЕ левый край картинки, вопреки документации
    Plotly и вопреки первой версии этой функции. Проверено 12.08.2026 через
    `getScreenCTM()` в браузере: паспортный x=0 у аннотации на категориальной
    оси совпал с ЛЕВЫМ КРАЕМ ОБЛАСТИ ПОСТРОЕНИЯ (после margin.l), а не
    с краем изображения. Из-за этого подписи стартовали внутри margin.l,
    но заканчивались ЗА его пределами — заходили на полосы (замерено:
    заход до 172 px у длинных названий отраслей).

    Лечится опорой на `xref="x domain"` — это по определению Plotly ровно
    начало области построения, здесь двусмысленности нет. Смещаемся от неё
    НАЗАД (отрицательным `xshift`) на ширину, которой хватает под самую
    длинную подпись, — тем самым запасом, что вернёт вызывающая сторона
    и передаст в `build()` для того же самого margin.l: числа одни и те же,
    разъехаться им неоткуда.
    """
    categories = list(fig.data[0].y) if fig.data else []
    reserve = _left_align_reserve(categories)

    fig.update_yaxes(showticklabels=False, automargin=False)
    for label in categories:
        fig.add_annotation(
            text=str(label),
            xref="x domain", x=0, xshift=-reserve, xanchor="left",
            yref="y", y=label, yanchor="middle",
            showarrow=False, align="left",
            font=dict(size=LEFT_ALIGN_FONT_PX, color=NEUTRAL_INK),
        )
    return reserve


def _grid_across_bars(fig: go.Figure) -> None:
    """Оставляет сетку только ПОПЕРЁК полос, вдоль — убирает.

    Просьба пользователя 07.08.2026: «без горизонтальных линий, вертикальные
    можно оставить». Сказано про рейтинг регионов — там полосы лежат, и линии
    вдоль них (по одной на каждую из двадцати областей) ничего не измеряют,
    а только рябят.

    Правило поэтому общее, но зависит от направления полос, а не от названия
    оси: сетка нужна там, где значения, и не нужна там, где подписи.
    У лежащих полос это значит «убрать горизонтальные», у стоящих — ровно
    наоборот: подписи у них внизу, и лишними становятся вертикальные
    (замерено на «Выдано гарантий — по годам»: 17 линий между годами).

    Виды, собранные не из полос (точки, ящик, карта), не трогаем: у них
    обе оси числовые, и сетка нужна на обеих.
    """
    bars = [t for t in fig.data if t.type == "bar"]
    if not bars:
        return
    if all(getattr(t, "orientation", None) == "h" for t in bars):
        fig.update_yaxes(showgrid=False)
    elif all(getattr(t, "orientation", None) != "h" for t in bars):
        fig.update_xaxes(showgrid=False)


#: Тон показателя -> какой цвет темы берёт его диаграмма.
#:
#: Цветов три, и они те же, что на главной: зелёный (`accent`), золотой
#: (`accent_2`), бирюзовый (`accent_3`). Раздаются ПО ПОКАЗАТЕЛЮ, а не по
#: месту в сетке (решено с пользователем 11.08.2026): цвет тогда работает
#: подсказкой — выпуск продукции всегда зелёный, рабочие места золотые,
#: и график узнаёшь, не читая заголовок.
#:
#: !! Сам тон живёт в `config.yaml` у показателя (`tone: 1|2|3`), а не
#: в коде — по общему правилу проекта: показатели описываются в реестре.
#: Не задан — берётся первый цвет, как было раньше.
TONE_KEYS = {1: "accent", 2: "accent_2", 3: "accent_3"}


def _tone_color(indicator: str, settings: dict) -> str:
    """Цвет диаграммы показателя: из темы по номеру тона."""
    try:
        meta = data.get_indicator_meta(indicator)
    except KeyError:                       # показателя нет в реестре
        return settings["accent"]
    key = TONE_KEYS.get(meta.get("tone"), "accent")
    return settings.get(key) or settings["accent"]


def indicator_color(indicator: str) -> str:
    """Тот же цвет, но снаружи — для разметки рядом с диаграммой.

    !! Существует ради ОДНОГО правила: цвет карточки и цвет её диаграммы
    обязаны совпасть, а значит считаться одной функцией, а не двумя
    похожими. Герой-карточка на странице раздела стоит вплотную к своему
    графику; посчитай она тон сама (хоть бы и по той же таблице `TONE_KEYS`),
    первое же изменение правила развело бы их по цвету, и ошибка вылезла бы
    не сообщением, а несовпадающей заливкой — то есть глазами и не сразу.

    !! Имя выбрано так, чтобы НЕ столкнуться с `tone_color()` ниже в этом
    же файле: та берёт НОМЕР тона и раздаёт цвета по другому правилу
    (тон 3 у неё — затемнённое золото, а не бирюза), потому что служит
    карточкам главной. Сначала функция называлась так же, и Python молча
    оставил ту, что ниже по файлу: вызов уходил в неё со строкой вместо
    числа, ни с чем не совпадал и возвращал зелёный. Ошибки не было —
    все четыре карточки СЭЭ просто оказались одного цвета (поймано
    17.08.2026 замером цвета в браузере, глазами это выглядело
    как «так и задумано»).
    """
    return _tone_color(indicator, theme.get_theme())


def _title_lines(fig: go.Figure) -> int:
    """Сколько строк в заголовке готовой фигуры (минимум одна)."""
    text = (fig.layout.title.text or "") if fig.layout.title else ""
    return text.count("<br>") + 1


def build(chart_type: str, indicator: str, year, regions, log: bool = False,
          height: int | None = None, program: str | None = None,
          recent_years: int | None = None,
          columns: int | None = None, monthly: pd.DataFrame | None = None,
          monthly_is_test: bool = False,
          compact_years: bool = False) -> go.Figure:
    """Собирает выбранную диаграмму и навешивает общее оформление.

    height — высота в пикселях. Задан (виджет на главной со своим пресетом
    размера) — диаграмма подгоняется под него, даже если вид просил себе
    другую высоту. Не задан (страница «Разбор», один график во весь экран) —
    вид оставляет свою, а если не просил — 700, как было.

    recent_years — только для вида «Годы» (`years_total`), остальные
    молча игнорируют. См. `Ctx.recent_years`.
    """
    entry = _REGISTRY.get(chart_type) or _REGISTRY["bar"]
    # Год один на весь сайт, а показатели кончаются в разные годы: гарантии
    # доходят до 2026-го, разрез СЭЭ по областям обрывается на 2024-м. Раньше
    # несовпадение давало пустые оси, и понять, сломано это или данных правда
    # нет, было нечем. Теперь слой данных подставляет ближайший год с числами,
    # а заголовок пишет, что год подставлен (см. `Ctx.title`).
    asked = int(year)
    shown = data.resolve_year(indicator, asked, program)
    ctx = Ctx(
        indicator=indicator,
        year=shown if shown is not None else asked,
        regions=regions or None,
        log=bool(log) and entry["log_ok"],
        program=program,
        asked_year=asked,
        recent_years=recent_years,
        cut=entry.get("cut", ""),
        columns=columns,
        monthly=monthly,
        monthly_is_test=monthly_is_test,
        compact_years=compact_years,
    )
    # Оформление сайта распространяется и на диаграммы: иначе страница была
    # бы одним шрифтом, а подписи внутри графиков — другим. Тему спрашиваем
    # здесь, в единственном общем месте, а не в каждой из 17 функций.
    settings = theme.get_theme()
    palette = [_tone_color(indicator, settings), *_PALETTE_TAIL]

    # !! Цвет приходится задавать ДО постройки, и вот почему: plotly express
    # вписывает цвет прямо в ряд данных, а не берёт его из разметки в момент
    # показа. Поэтому layout.colorway на столбцы уже не влияет (проверено
    # в браузере: столбцы оставались синими #636efa). px.defaults —
    # единственный способ поменять палитру всем 17 видам разом, не трогая
    # каждую функцию.
    px.defaults.color_discrete_sequence = palette

    fig = entry["builder"](ctx)

    # !! Дефолтный шаблон plotly (`layout.template`) снят: express вписывает
    # его в каждую фигуру сам, а это десяток неиспользуемых цветовых шкал
    # (histogram2dcontour, heatmap, surface...) — на сайте только bar,
    # scatter, pie и карта вручную на голых осях. Цвет, сетку, фон и шрифт
    # ниже и так задаём явно, шаблону тут нечего решать, кроме лишних
    # килобайт в каждом ответе. Замерено 12.08.2026: 12 фигур раздела СЭЭ
    # везли этот дубль 12 раз подряд.
    fig.layout.template = None

    # !! Левое поле шире, если билдер спрятал подписи оси и нарисовал их
    # сам через `_left_align_categories` (СЭЭ, 11.08.2026) — тогда обычные
    # 10 px нечем заполнить, а надписи-«список» нуждаются в месте под свою
    # ширину. `automargin` тут не помощник: он меряет ВИДИМЫЕ элементы оси,
    # а подписи оси спрятаны (`showticklabels=False`) — automargin посчитал
    # бы, что мерить нечего, и не попросил бы ни пикселя.
    left_margin = 10
    if fig.layout.yaxis.showticklabels is False and fig.data:
        # !! `fig.data[0].y` — массив numpy (колонка из pandas), а не список:
        # `list(y)` — универсальный способ получить из него обычный список
        # что для numpy-массива, что для None (list(None) упал бы, поэтому
        # проверка на None остаётся первой).
        y = fig.data[0].y
        left_margin = _left_align_reserve(list(y) if y is not None else [])

    # !! Правое поле нужно ТОЛЬКО горизонтальным полосам («Полосы — рейтинг»
    # и похожие) — там число подписано у конца полосы, справа. У вертикальных
    # видов («Динамика по годам» и остальные 20+) справа нет ничего: подпись
    # либо внутри столбца, либо над ним. Формула ниже раньше не различала
    # ориентацию и резервировала 120 px и вертикальным видам тоже — на
    # «широком» пресете (12 колонок) это была четверть высоты столбца шириной
    # пустоты справа от последнего года (снимок пользователя 18.08.2026).
    horizontal = bool(fig.data) and getattr(fig.data[0], "orientation", None) == "h"
    right_margin = int((columns or TITLE_FULL_COLUMNS) * 10) if horizontal else 16

    fig.update_layout(
        # !! Цвет текста здесь — ЗАПАСНОЙ. Настоящий ставит CSS в браузере
        # (`assets/custom.css`, блок «Текст внутри диаграмм»), потому что
        # только браузер знает выбранную тему. Одним нейтральным серым
        # обойтись нельзя: замер 11.08.2026 показал, что ни один оттенок
        # не даёт 4,5 : 1 разом на светлой поверхности (#eae9e9) и тёмной
        # (#1c1a19) — лучшее, что выходит, это 3,9 / 3,7.
        font=dict(family=theme.font_stack(settings), color=NEUTRAL_INK,
                  size=CHART_FONT_PX),
        # Для видов, собранных не через express, а руками на go.Figure:
        # у них цвет ряда не задан, и они берут его отсюда
        colorway=palette,
        # !! Поле сверху считается по ЧИСЛУ СТРОК заголовка, а не числом.
        # Заголовок рисуется внутри верхнего поля: две строки в поле
        # на одну наезжают на область графика. Читаем готовый текст фигуры,
        # поэтому правило работает и для видов, которые пишут заголовок
        # сами («— по месяцам 2026 года»), а не берут `Ctx.title`.
        # Заголовок помельче умолчания (17 px): он занимает верхнее поле,
        # а в тесном виджете каждый десяток пикселей идёт подписям категорий.
        # В оригинальном портале заголовок тоже мелкий.
        title_font=dict(size=TITLE_FONT_PX),
        # !! Поле снизу зависит от того, показана ли ось значений. У видов,
        # где число подписано у самой полосы, ось скрыта — держать под неё
        # 40 px значило бы отнимать их у подписей категорий.
        # !! Правое поле — под числа у концов полос, и оно ТОЖЕ зависит
        # от ширины виджета. Фиксированные 120 px подбирались под диаграмму
        # во всю ширину; на половинной карточке (464 px) они съедали
        # четверть, а вместе с подписями отраслей не оставляли полосам
        # и сотни пикселей (замерено 11.08.2026).
        margin=dict(l=left_margin, r=right_margin,
                    b=40 if fig.layout.xaxis.visible is not False else 16,
                    t=TITLE_MARGIN_BASE + TITLE_LINE_H * _title_lines(fig)),
        # !! Фон прозрачный, а не белый, и это про тёмную тему. Тему человек
        # выбирает в браузере (localStorage), сервер о ней не знает и одну
        # и ту же фигуру отдаёт обоим. Белая подложка на тёмной странице
        # была бы светлой заплатой; прозрачная принимает цвет карточки.
        plot_bgcolor="rgba(0,0,0,0)",
        paper_bgcolor="rgba(0,0,0,0)",
        # !! Протяжка мышью по диаграмме БОЛЬШЕ НЕ ПРИБЛИЖАЕТ (10.08.2026).
        # Умолчание plotly — `dragmode="zoom"`: движение мыши с зажатой
        # кнопкой над полем графика приближает выделенный прямоугольник.
        # Само по себе не беда, но панель инструментов у нас скрыта везде
        # (`displayModeBar: False`), а вместе с ней и кнопка «сбросить оси» —
        # выбраться из случайного приближения человеку нечем, и график
        # остаётся сломанным до перезагрузки страницы. Так и вышло у СЭЭ:
        # вместо пятнадцати лет на экране оставалось семь, последний столбец
        # обрезан краем (воспроизведено протяжкой в браузере 10.08.2026).
        # Подсказки при наведении от этого не страдают — они не про drag.
        dragmode=False,
        # Русская типографика чисел: запятая для дробей, неразрывный пробел
        # для разрядов. Иначе plotly пишет по-английски: 454,416.0
        separators=", ",
    )
    # Сетка и оси — полупрозрачным серым по той же причине: он читается
    # и на светлом, и на тёмном, а фиксированный цвет пришлось бы менять
    # вместе с темой, то есть протаскивать её в каждый коллбэк.
    #
    # Сама сетка пунктирная; нулевая линия остаётся сплошной — она не
    # разметка, а начало отсчёта, и путать её с делениями не нужно
    fig.update_xaxes(gridcolor=GRID_COLOR, griddash=GRID_DASH,
                     zerolinecolor=NEUTRAL_GRID)
    fig.update_yaxes(gridcolor=GRID_COLOR, griddash=GRID_DASH,
                     zerolinecolor=NEUTRAL_GRID)

    # У компактной годовой диаграммы нет ни правых значений, ни шкалы Y:
    # штатное поле под них оставляло столбцы узкой группой посередине.
    # Отдаём это место данным и слегка уплотняем интервалы между годами.
    if compact_years:
        fig.update_layout(
            margin=dict(l=12, r=12, t=48, b=28),
            title_font=dict(size=15),
            bargap=0.12,
        )

    # !! Единица измерения на диаграмме теперь ровно ОДНА, и она в заголовке
    # (17.08.2026, `Ctx.title`). Прежде их было до трёх сразу: надпись
    # в правом верхнем углу, заголовок оси значений и «млрд ₸» в подписи
    # КАЖДОГО столбца. Здесь снимаются две из трёх — угловая надпись убрана
    # целиком, заголовки осей гасятся у всех разделов, а не только у СЭЭ,
    # как было с 11.08.2026.
    #
    # Почему заголовки осей гасятся, а не оставлены «хотя бы на одной оси»:
    # у полос (bar/industries) ось значений скрыта (`visible=False`), но её
    # ЗАГОЛОВОК всё равно рисуется — `visible=False` прячет линию, деления
    # и подписи делений, но не `title` (замерено 11.08.2026: «ед.» висело
    # в правом верхнем углу поверх заголовка). У «Динамики по годам» ось,
    # наоборот, видна, и там «млрд ₸» налезало на цифры шкалы, потому что
    # `automargin` для неё не задан. Обе беды снимаются одной строкой,
    # и после переноса единицы в заголовок терять нечего.
    fig.update_xaxes(title_text="")
    fig.update_yaxes(title_text="")

    _grid_across_bars(fig)

    if height:
        # Пресет виджета сильнее собственной высоты вида: на экране из
        # нескольких виджетов сетку задаёт раскладка, а не диаграмма
        fig.update_layout(height=int(height))
    elif fig.layout.height is None:  # вид мог задать свою высоту
        fig.update_layout(height=700)
    return fig


#: Ниже этого размера подписи внутри секторов читать невозможно.
#:
#: !! Было 12 (то есть шрифт 13). При таком размере plotly **прятал две
#: подписи** — «Западно-Казахстанская» и «Восточно-Казахстанская»: они
#: длиннее остальных и не влезали в свой сектор, а режим `hide` убирает
#: то, что не влезло, целиком. Сектор оставался, подпись исчезала.
#: Замерено в браузере (27.07.2026) на высотах 700, 420 и 320 px:
#: при 13 px прячутся ровно эти две на любой высоте, при 11 px — ни одной.
#: Поэтому 10 (шрифт 11): два пикселя размера в обмен на две подписи.
MIN_LABEL_SIZE = 10


def _size_floor(values: pd.Series) -> float:
    """Минимальный размер сектора — доля от самого крупного.

    Осознанный компромисс: у мелких регионов сектор растягивается до порога,
    иначе подпись в него не помещается и вылезает поверх соседей.

    Чтобы это не превращалось в обман, соблюдаются два правила:
    числа в подписи и в подсказке — **всегда настоящие**, а в заголовке
    появляется пометка, что размеры подтянуты. Порог задаётся в config.yaml,
    ключ `charts.min_slice_percent`; 0 отключает подтягивание совсем.
    """
    percent = float(
        data.load_config().get("charts", {}).get("min_slice_percent", 0)
    )
    if percent <= 0 or values.empty:
        return 0.0
    return float(values.max()) * percent / 100


def _label(value: float, ctx: "Ctx") -> str:
    """Настоящее значение строкой: разряды пробелом, единица в конце."""
    shown = value / ctx.meta["divisor"]
    text = f"{shown:,.{ctx.meta['decimals']}f}".replace(",", " ")
    return f"{text} {ctx.meta['display_unit']}".strip()


def _adjusted_note(raised: int, ctx: "Ctx") -> str:
    """Пометка в заголовок, если размеры пришлось подтянуть."""
    if not raised:
        return ""
    percent = data.load_config().get("charts", {}).get("min_slice_percent", 0)
    return f"<br><sub>у {raised} регионов сектор увеличен до {percent} % — числа настоящие</sub>"


def _flat_nodes(ctx: "Ctx") -> tuple[pd.DataFrame, int]:
    """Плоский список регионов для круговой и плиток."""
    df = data.get_regions(ctx.indicator, ctx.year, regions=ctx.regions, program=ctx.program).copy()
    floor = _size_floor(df["value"])
    df["display"] = df["value"].clip(lower=floor)
    df["подпись"] = [_label(v, ctx) for v in df["value"]]
    return df, int((df["value"] < floor).sum())


#: Что показать, когда за выбранный год у показателя нет данных.
#: Источники разной длины: выгрузка МСП — 2024–2025, таблицы БД — 2022–2026.
NO_DATA = "За этот год у показателя нет данных.<br>Выберите другой год или показатель."


def _tree_nodes(ctx: "Ctx") -> tuple[pd.DataFrame, int]:
    """Узлы для лучей и сосулек: макрорегионы и области.

    Строим вручную, а не через `px`, чтобы у каждого узла — включая
    макрорегионы — были и подтянутый размер, и настоящее значение в подписи.
    """
    df = data.get_regions_grouped(ctx.indicator, ctx.year, regions=ctx.regions, program=ctx.program)
    if df.empty:
        return pd.DataFrame(columns=["id", "label", "parent", "value", "display", "подпись"]), 0
    floor = _size_floor(df["value"])

    rows: list[dict] = []
    for macro, group in df.groupby("macroregion"):
        leaves = [
            {
                "id": f"{macro}/{row['region']}",
                "label": row["region"],
                "parent": macro,
                "value": float(row["value"]),
                "display": max(float(row["value"]), floor),
            }
            for _, row in group.iterrows()
        ]
        rows.extend(leaves)
        rows.append(
            {
                "id": macro,
                "label": macro,
                "parent": "",
                "value": float(group["value"].sum()),
                # Родитель обязан быть суммой детей, иначе plotly ругается
                "display": sum(leaf["display"] for leaf in leaves),
            }
        )

    nodes = pd.DataFrame(rows)
    nodes["подпись"] = [_label(v, ctx) for v in nodes["value"]]
    return nodes, int((df["value"] < floor).sum())


def _hierarchy_style(fig: go.Figure, size: int = MIN_LABEL_SIZE + 1) -> go.Figure:
    """Общее для круговой, плиток, лучей и сосулек: размер шрифта подписей.

    `size` — на случай, когда виду тесно даже при общем размере. Такой вид
    один, «сосульки»: там ширина ячейки пропорциональна значению, и у самых
    маленьких областей места под подпись меньше, чем у остальных.

    Режим `hide` значит: то, что не влезло, plotly **убирает целиком** —
    сектор остаётся, подпись исчезает. Это осознанный выбор: альтернатива —
    подписи, налезающие друг на друга и на соседние сектора. Но раз уж
    исчезновение молчаливое, размер подобран замером, а не на глаз.
    """
    fig.update_traces(insidetextfont=dict(size=size))
    fig.update_layout(uniformtext=dict(minsize=size - 1, mode="hide"))
    return fig


def message(text: str) -> go.Figure:
    """Та же пустая фигура с текстом, но для страниц.

    Нужна главной: если набор виджетов изменили в другой вкладке, на месте
    исчезнувшего виджета честнее показать надпись, чем пустой прямоугольник.
    """
    return _message(text)


def tone_color(tone: int = 1) -> str:
    """Цвет по номеру оттенка: 1 — основной, 2 — второй, 3 — второй тёмный.

    Витрина инструментов на главной красится не одним цветом, а тремя,
    как в макете. Номер оттенка живёт в макете (core/mockup.py), а какой
    это цвет сегодня — знает тема. Так перекраска сайта из настроек
    доезжает и до карточек инструментов.
    """
    settings = theme.get_theme()
    if tone == 2:
        return settings["accent_2"]
    if tone == 3:
        return theme.mix(settings["accent_2"], "#000000", 0.4)
    return settings["accent"]


def pace_gauge(percent: float, expected: float, tone: int = 1,
               height: int = 130) -> go.Figure:
    """Полукруглая шкала «сколько освоено» с отметкой ожидаемого темпа.

    Главная мысль макета: сама по себе цифра «48 %» ни о чём не говорит —
    важно, сколько должно быть освоено к сегодняшнему дню. Поэтому поперёк
    шкалы стоит засечка ожидаемого темпа: заливка не дотянула до неё —
    отставание, перешла — идём с опережением.

    !! Кольцо (а не залитый полукруг) получается связкой двух вещей:
    у полосы задана `thickness`, и ровно такая же `thickness` задана
    подложке-ступени. Без ступени `bgcolor` заливает весь полукруг целиком,
    и вместо тонкой дуги выходит сплошной сектор (проверено в браузере).
    """
    color = tone_color(tone)
    thickness = 0.32
    fig = go.Figure(go.Indicator(
        mode="gauge+number",
        value=percent,
        number={"suffix": " %", "valueformat": ".1f",
                "font": {"size": 30, "color": color}},
        gauge={
            "axis": {"range": [0, 100], "visible": False},
            "bar": {"color": color, "thickness": thickness},
            "bgcolor": "rgba(0,0,0,0)",
            "borderwidth": 0,
            # Подложка кольца — та самая ступень во всю шкалу
            "steps": [{"range": [0, 100], "color": "#eae7e7",
                       "thickness": thickness}],
            "threshold": {
                "value": expected,
                "thickness": 1,
                "line": {"color": "#201e1d", "width": 3},
            },
        },
    ))
    fig.update_layout(
        height=height,
        margin=dict(l=10, r=10, t=6, b=0),
        paper_bgcolor="rgba(0,0,0,0)",
        font=dict(family=theme.font_stack()),
        separators=", ",
    )
    return fig


def _message(text: str) -> go.Figure:
    """Пустая фигура с текстом — вместо падения, когда рисовать нечего."""
    fig = go.Figure()
    fig.add_annotation(
        text=text, showarrow=False, xref="paper", yref="paper", x=0.5, y=0.5,
        font=dict(size=14), align="center",
    )
    fig.update_xaxes(visible=False)
    fig.update_yaxes(visible=False)
    return fig


