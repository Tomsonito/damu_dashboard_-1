#: Сколько знаков названия отрасли влезает в подпись, НА КОЛОНКУ сетки.
#: Полное название остаётся в подсказке при наведении.
#:
#: !! Зависит от ширины виджета, а не одно число на всех (11.08.2026).
#: Прежние 32 знака подбирались под диаграмму во всю ширину. Когда
#: «Отрасли» встали по две в ряд, замер показал беду: подпись занимала
#: 232 px из 464, справа ещё 120 px под числа — самим полосам оставалось
#: 102 px, то есть меньше четверти. На экране 1024 бюджет и вовсе уходил
#: в минус. Теперь 12 колонок дают прежние 32 знака, 6 — шестнадцать.
INDUSTRY_LABEL_CHARS_PER_COLUMN = 2.7


def _industry_label(name: str, columns: int | None = None) -> str:
    """Короткая подпись отрасли: буква секции ОКЭД и урезанное название.

    В источнике названия длиной до 78 знаков («E-Водоснабжение;
    канализационная система, контроль над сбором и распределением
    отходов»). Целиком они съедали половину ширины графика, а сами полосы
    сжимались в чёрточки; часть подписей при этом всё равно обрезалась
    с левого края (замерено 07.08.2026).

    Буква секции остаётся всегда: она короткая, стоит в начале и по ней
    отрасль узнают те, кто работает с ОКЭД каждый день.
    """
    limit = int((columns or TITLE_FULL_COLUMNS) * INDUSTRY_LABEL_CHARS_PER_COLUMN)
    code, _, rest = str(name).partition("-")
    if len(code) > 2 or not rest.strip():      # не вида «C-…» — берём как есть
        code, rest = "", str(name)
    rest = rest.strip()
    if len(rest) > limit:
        rest = rest[:limit - 1].rstrip(" ,;.") + "…"
    return f"{code} · {rest}" if code else rest


#: Виды-«разрезы» и колонка фактов, по которой каждый режет.
#:
#: !! Таблица нужна затем, что один и тот же разрез показывается ДВУМЯ
#: способами: полосами-дивами на странице раздела (17.08.2026) и диаграммой
#: Plotly на «Разборе». Оба обязаны брать одни и те же строки, поэтому
#: «какой колонкой режет этот вид» знает одно место, а не два.
CUT_COLUMNS = {
    "bar": "region",
    "industries": "industry",
    "industries_alpha": "industry",
    "banks": "bank",
    "subjects": "subject_type",
    "purposes": "loan_purpose",
    "programs": "source_program",
}

#: Порядок строк разреза. По умолчанию — по значению (крупнее сверху);
#: у отраслей есть вариант по алфавиту, он же по коду секции ОКЭД.
CUT_SORT = {"industries_alpha": "alpha"}


def is_cut(chart_type: str) -> bool:
    """Вид режет данные по колонке и показывается полосами?"""
    return chart_type in CUT_COLUMNS


def cut_frame(indicator: str, year: int, column: str,
              regions: list[str] | None = None,
              program: str | None = None) -> pd.DataFrame:
    """Строки разреза: сама колонка, `value` и готовая подпись `label`.

    !! ЕДИНСТВЕННЫЙ источник строк для разреза — и для полос-дивов
    на странице раздела, и для диаграммы Plotly на «Разборе». Считай их
    два места по отдельности, и однажды они разойдутся: у регионов свой
    вход в данные (`get_regions`), у остальных разрезов общий
    (`get_breakdown`), и повторить эту развилку во второй раз — значит
    завести второе место, где её можно забыть.
    """
    if column == "region":
        df = data.get_regions(indicator, year, regions=regions, program=program)
    else:
        df = data.get_breakdown(indicator, year, column,
                                regions=regions, program=program)
    if df.empty:
        return pd.DataFrame(columns=[column, "value", "label"])
    df = df.copy()
    df["label"] = df[column].astype(str)
    return df


def cut_title(chart_type: str, indicator: str, year: int,
              program: str | None = None, columns: int | None = None) -> str:
    """Заголовок разреза — ТОЙ ЖЕ функцией, что и у диаграммы (`Ctx.title`).

    Полосы-дивы не строят фигуру, но подписаны обязаны быть одинаково
    с Plotly: и разрез в названии, и единица в скобках, и пометка
    о подставленном годе. Свой заголовок рядом означал бы, что один
    и тот же разрез на «Разборе» и в разделе называется по-разному.
    """
    entry = _REGISTRY.get(chart_type) or {}
    asked = int(year)
    shown = data.resolve_year(indicator, asked, program)
    ctx = Ctx(
        indicator=indicator,
        year=shown if shown is not None else asked,
        regions=None, program=program, asked_year=asked,
        cut=entry.get("cut", ""), columns=columns,
    )
    return ctx.title


def _breakdown(column: str, shorten=None, sort: str = "value"):
    """Собирает вид «рейтинг по разрезу»: полосы с числом у каждой.

    Один и тот же график нужен четырём разрезам — отрасли, банки,
    субъектность, цели займа. Отличаются они только колонкой и тем, надо ли
    сокращать подписи, поэтому вместо четырёх почти одинаковых функций
    здесь одна, а `@chart` регистрирует её четыре раза с разными
    параметрами.

    `sort` — порядок полос: `"value"` (было и остаётся умолчанием — крупнее
    сверху) или `"alpha"` (по первой букве подписи; заведено 13.08.2026
    для отраслей — код секции ОКЭД стоит первым символом, и алфавитный
    порядок превращается в порядок по коду A, B, C…).

    Ось значений скрыта намеренно. Число подписано у каждой полосы, и ось
    под ними повторяла бы ту же информацию второй раз — а места на неё
    уходило столько, что подписи делений разворачивало вертикально
    (было видно на скриншоте 07.08.2026). Полоса плюс её число читаются
    без оси; за точным сравнением есть подсказка при наведении.
    """

    def builder(ctx: Ctx) -> go.Figure:
        # Строки берём общей `cut_frame` — той же, что и полосы-дивы
        # на странице раздела. Разбор, зачем так, — в её шапке
        df = cut_frame(ctx.indicator, ctx.year, column,
                       regions=ctx.regions, program=ctx.program)
        if df.empty:
            return _message(NO_DATA)

        df = ctx.scaled(df)
        # Сокращение зависит от ширины виджета — она известна из пресета
        df["label"] = ([shorten(v, ctx.columns) for v in df[column]] if shorten
                       else df[column].astype(str))
        return _breakdown_figure(df, ctx, column, sort)

    return builder


def _breakdown_figure(df, ctx: Ctx, column: str, sort: str = "value") -> go.Figure:
    fig = px.bar(
        df, x="shown", y="label", orientation="h", text="текст",
        custom_data=[column],
        labels={"shown": ctx.unit, "label": ""}, title=ctx.title,
    )
    fig.update_traces(
        textposition="outside",
        # Подпись рисуется за краем области построения — иначе plotly
        # прячет ту, что не влезла, и полоса остаётся без числа
        cliponaxis=False,
        textfont_size=11,
        # Тонкие полосы с зазором: сплошная заливка во всю строку читается
        # тяжело, а разницу длин видно одинаково при любой толщине
        width=0.62,
        marker_line_width=0,
        hovertemplate="<b>%{customdata[0]}</b><br>%{text}<extra></extra>",
    )
    # Самая длинная полоса не должна упираться в край: справа от неё стоит
    # число, и без запаса оно наезжает на границу карточки
    #
    # !! Ось начиналась ЖЁСТКО с нуля (`range=[0, ...]`) — верно, пока все
    # значения одного знака, а у «Создано раб. мест» по отраслям СЭЭ это
    # не так: часть отраслей в 2024-м в минусе (сокращение мест больше
    # найма — проверено в исходном Excel, это данные источника, не сбой
    # разбора). Столбец с отрицательным значением рос БЫ влево от нуля,
    # но диапазон его туда не пускал — столбец и подпись у него пропадали
    # с экрана молча: ни ошибки, ни пустой строки, просто дыра в списке
    # (поймано пользователем 13.08.2026 — «у некоторых пунктов нет
    # показателей»). Тот же класс бага, что уже был с подписями категорий
    # (см. `CATEGORY_TICKS`): график рисуется без единой ошибки, врёт
    # только то, что не поместилось в жёстко заданный диапазон.
