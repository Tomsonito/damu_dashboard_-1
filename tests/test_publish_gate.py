"""Шлюз публикации в 9:00 — чистая арифметика по времени.

Почему именно эти функции. Вся отложенная публикация держится на одном
неравенстве «штамп правки < последний наступивший рубеж», и оно уходит
прямо в SQL. Ошибись здесь на день — и свежие данные либо не выйдут вовсе,
либо выйдут сразу, минуя сутки на отмену. Проверить это глазами нельзя:
чтобы увидеть ошибку вживую, надо дождаться утра.

Обе функции чистые — принимают момент времени и ничего не читают,
поэтому тесты идут без хранилища.
"""

from datetime import datetime

from core import publish


def test_ближайшая_публикация_сегодня_если_ещё_нет_девяти():
    """Правка в 8:59 выйдет сегодня же в 9:00."""
    moment = publish.next_publish_time(datetime(2026, 8, 11, 8, 59))
    assert moment == datetime(2026, 8, 11, 9, 0)


def test_ближайшая_публикация_завтра_если_девять_уже_прошло():
    """Правка в 9:01 ждёт СЛЕДУЮЩЕГО утра — сутки на отмену остаются."""
    moment = publish.next_publish_time(datetime(2026, 8, 11, 9, 1))
    assert moment == datetime(2026, 8, 12, 9, 0)


def test_ровно_девять_считается_как_уже_прошедшее():
    """Граница принадлежит прошлому: в 9:00:00 сегодняшний рубеж наступил.

    Иначе правка, сделанная ровно в девять, опубликовалась бы мгновенно.
    """
    assert publish.next_publish_time(datetime(2026, 8, 11, 9, 0)) == \
        datetime(2026, 8, 12, 9, 0)


def test_последний_рубеж_зеркалит_ближайший():
    """`last_deadline` — обратная сторона `next_publish_time`.

    До девяти утра последним наступившим рубежом остаётся вчерашний,
    после девяти — сегодняшний.
    """
    assert publish.last_deadline(datetime(2026, 8, 11, 8, 59)) == \
        datetime(2026, 8, 10, 9, 0)
    assert publish.last_deadline(datetime(2026, 8, 11, 9, 0)) == \
        datetime(2026, 8, 11, 9, 0)


def test_простой_сервера_не_теряет_публикацию():
    """Сервер лежал двое суток — рубеж всё равно считается наступившим.

    Это главное свойство шлюза: он не «срабатывает в 9:00», а отвечает
    на вопрос «что уже дозрело». Правка от 9-го числа обязана быть
    опубликована при первом же подъёме 11-го.
    """
    stamp = datetime(2026, 8, 9, 15, 0)          # правка днём 9-го
    deadline = publish.last_deadline(datetime(2026, 8, 11, 10, 0))
    assert stamp < deadline, "правка двухдневной давности обязана дозреть"


def test_подпись_про_время_публикации():
    """«сегодня» и «завтра» — для человека, дата — для всего остального."""
    now = datetime(2026, 8, 11, 10, 0)
    assert publish.describe_publish_time(datetime(2026, 8, 11, 9, 0), now) == \
        "сегодня в 09:00"
    assert publish.describe_publish_time(datetime(2026, 8, 12, 9, 0), now) == \
        "завтра в 09:00"
    assert publish.describe_publish_time(datetime(2026, 8, 20, 9, 0), now) == \
        "20.08 в 09:00"
