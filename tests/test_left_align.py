"""Подписи регионов/отраслей СЭЭ соответствуют своим данным.

!! Только один тест — остальные, что были здесь раньше (выравнивание,
отступы, ширина поля), убраны 12.08.2026 по правилу пользователя: тест
пишем там, где цена ошибки — неверные ЦИФРЫ на экране, а не там, где
дело в пикселях. Кривой отступ виден и чинится замером в браузере;
для этого теста не нужен.

Этот тест — другое: если подписи и данные разойдутся, пользователь
увидит НЕ ТУ область рядом с полосой — то есть перепутанные данные,
а не просто некрасиво.
"""

import pytest

from core import charts


@pytest.mark.needs_storage
def test_подписи_see_совпадают_со_своими_данными():
    """Каждой полосе — подпись именно её категории, ни одной лишней/потерянной.

    Раньше (до 12.08.2026) названия рисовала сама ось Y — соответствие
    подписи и полосы гарантировал Plotly. Теперь подписи рисуются отдельно
    (`_left_align_categories`), и их набор надо явно сверять с данными:
    расхождение здесь означает не кривой пиксель, а область, подписанную
    чужим названием.
    """
    fig = charts.build("bar", "see_output", 2026, None,
                       program="СЭЭ", height=700, columns=12)
    categories = list(fig.data[0].y)
    assert len(fig.layout.annotations) == len(categories)
    assert {a.text for a in fig.layout.annotations} == {str(c) for c in categories}
