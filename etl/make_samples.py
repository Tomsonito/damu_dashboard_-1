"""Генератор демонстрационных данных для макета навигации.

Зачем он появился. Разделов на сайте два десятка («План освоения»,
«Гар. выдача», «Суб. выдача» и так далее), а в боевой базе пока лежат
только бюджетные показатели по областям. Чтобы собрать и показать макет
многораздельного дашборда, разделы надо чем-то наполнить.

**Это выдуманные числа.** Они не имеют отношения к настоящим показателям
Фонда и годятся только для проверки вёрстки и навигации. Устройство
выбрано так, чтобы спутать их с настоящими было тяжело, а выключить —
легко:

- пишутся в отдельную таблицу `demo_facts`, а не в общую `facts`;
  прогон настоящего ETL их не видит и не трогает;
- включаются флагом `demo_data` в `config.yaml` — одна строка, и сайт
  снова показывает только реальные цифры;
- у показателей свои коды (`demo_*`), поэтому сложиться с настоящими
  в одну сумму они не могут.

**Раздел лежит в колонке `program`.** Это не случайность: в таблице фактов
колонки `program` и `instrument` заведены с самого начала под будущие
разрезы и до сих пор пустуют. Когда придут настоящие данные по программам,
они лягут в ту же колонку — страницы переписывать не придётся, поменяется
только разборщик.

Запуск из корня проекта:

    python -m etl.make_samples          # создать Excel и загрузить в хранилище
    python -m etl.make_samples --excel  # только создать Excel, не загружать
"""

import argparse
import random
from datetime import date
from pathlib import Path

import pandas as pd

EXCEL_PATH = Path("data/raw/demo_показатели.xlsx")

#: Разделы будущего меню. Порядок — как на эскизе.
#: Раздел уезжает в колонку `program` таблицы фактов.
SECTIONS = [
    "План освоения",
    "СЭЭ",
    "Гар. выдача",
    "ГФ2",
    "Гар. — Осн. долг",
    "Кредит. выдача",
    "Өрлеу",
    "Суб. выдача",
    "Суб. — Осн. долг",
    "Суб. — Выплаты",
    "Фин. показатели",
    "Казначейство",
    "Закупки",
    "Риск-менеджмент",
    "Мониторинг",
    "Нефин. поддержка",
    "Маркетинг",
    "Пробл. активы",
    "Персонал",
    "СКПД",
]

#: Показатели — одни и те же во всех разделах (так решено: разделы
#: одинаковые). Ключ -> (название, единица, порядок величины на область
#: в месяц). Масштаб нужен, чтобы числа выглядели правдоподобно, а не
#: «1 234 567 рабочих мест».
INDICATORS = {
    "demo_plan":      ("План", "млн тенге", 4_000),
    "demo_fact":      ("Факт", "млн тенге", 3_200),
    "demo_issued":    ("Выдано", "млн тенге", 2_600),
    "demo_contracts": ("Договоров", "штук", 120),
    "demo_jobs":      ("Рабочих мест", "мест", 900),
}

#: Годы и последний загруженный месяц — как у настоящих данных:
#: 2026-й неполный, семь месяцев. Пусть макет ведёт себя так же.
YEARS = [2022, 2023, 2024, 2025, 2026]
LAST_MONTH_OF_CURRENT_YEAR = 7

#: Области — те же, что в настоящих данных. Читаются из хранилища,
#: чтобы написание совпадало до буквы (иначе карта не найдёт область).
FALLBACK_REGIONS = [
    "Абай", "Акмолинская", "Актюбинская", "Алматинская", "Атырауская",
    "Восточно-Казахстанская", "Жамбылская", "Жетісу", "Западно-Казахстанская",
    "Карагандинская", "Костанайская", "Кызылординская", "Мангистауская",
    "Павлодарская", "Северо-Казахстанская", "Туркестанская", "Ұлытау",
    "г. Алматы", "г. Астана", "г. Шымкент",
]

#: Зерно случайности зафиксировано: два запуска дают одинаковые числа.
#: Иначе каждый прогон менял бы все графики, и нельзя было бы понять,
#: изменилось что-то из-за правки кода или просто перекатились кости.
SEED = 20260727


def regions() -> list[str]:
    """Названия областей из хранилища; без него — запасной список."""
    try:
        from core import data

        found = data.get_region_choices()
        if found:
            return found
    except Exception:
        pass
    return FALLBACK_REGIONS


def _month_factor(month: int) -> float:
    """Сезонность: к концу года осваивают больше, чем в январе.

    Так ведут себя настоящие бюджетные показатели, и без этого помесячные
    диаграммы выглядели бы неестественно ровными.
    """
    return 0.6 + 0.08 * month


def _year_factor(year: int) -> float:
    """Медленный рост от года к году, около 8 % в год."""
    return 1.08 ** (year - YEARS[0])


def build() -> pd.DataFrame:
    """Собирает длинную таблицу демо-данных.

    Форма — как у общей таблицы фактов, только колонки названы по-русски:
    файл человек будет открывать глазами и, возможно, править руками.
    """
    rng = random.Random(SEED)
    region_names = regions()

    # У каждой области свой размер (столица и крупные области больше),
    # у каждого раздела — свой масштаб. Оба множителя постоянны для всего
    # прогона, поэтому области сохраняют относительный размер из месяца
    # в месяц — как в жизни, а не пляшут случайно.
    region_scale = {name: rng.uniform(0.55, 1.8) for name in region_names}
    section_scale = {name: rng.uniform(0.4, 2.2) for name in SECTIONS}

    rows: list[dict] = []
    for section in SECTIONS:
        for code, (title, unit, base) in INDICATORS.items():
            for year in YEARS:
                last_month = LAST_MONTH_OF_CURRENT_YEAR if year == YEARS[-1] else 12
                for month in range(1, last_month + 1):
                    for name in region_names:
                        value = (
                            base
                            * region_scale[name]
                            * section_scale[section]
                            * _year_factor(year)
                            * _month_factor(month)
                            * rng.uniform(0.85, 1.15)
                        )
                        rows.append(
                            {
                                "Раздел": section,
                                "Показатель": title,
                                "Код показателя": code,
                                "Единица": unit,
                                "Область": name,
                                "Год": year,
                                "Месяц": month,
                                "Значение": round(value, 1 if unit == "млн тенге" else 0),
                            }
                        )

    df = pd.DataFrame(rows)

    # Факт не может обгонять план — иначе «освоение 137 %» на каждом экране.
    # Правим уже собранную таблицу: берём план той же строки и оставляем
    # от него 60–95 %.
    key = ["Раздел", "Область", "Год", "Месяц"]
    plan = df[df["Код показателя"] == "demo_plan"].set_index(key)["Значение"]
    is_fact = df["Код показателя"] == "demo_fact"
    ratios = [rng.uniform(0.6, 0.95) for _ in range(int(is_fact.sum()))]
    fact_plan = df.loc[is_fact].set_index(key).index.map(plan)
    df.loc[is_fact, "Значение"] = (fact_plan.to_numpy() * ratios).round(1)

    return df


def save_excel(df: pd.DataFrame) -> None:
    """Кладёт таблицу в data/raw/ — оттуда её читает разборщик.

    Правило проекта: оригиналы в `data/raw/` не изменяются вручную. Здесь
    оно тоже действует, но с оговоркой — файл выдуманный, и если хочется
    поправить пару чисел «под показ», это ничего не испортит: разборщик
    возьмёт файл как есть.
    """
    EXCEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    df.to_excel(EXCEL_PATH, index=False, sheet_name="Данные")


def main() -> None:
    parser = argparse.ArgumentParser(description="Демо-данные для макета разделов")
    parser.add_argument(
        "--excel", action="store_true",
        help="только создать Excel, не загружать в хранилище",
    )
    args = parser.parse_args()

    df = build()
    save_excel(df)
    print(f"Excel готов: {EXCEL_PATH}")
    print(f"строк: {len(df):,}".replace(",", " "))
    print(f"разделов: {df['Раздел'].nunique()}, "
          f"показателей: {df['Код показателя'].nunique()}, "
          f"областей: {df['Область'].nunique()}, "
          f"годы: {df['Год'].min()}–{df['Год'].max()}")

    if args.excel:
        print("загрузка в хранилище пропущена (--excel)")
        return

    from etl import load_demo

    load_demo.load(EXCEL_PATH)


if __name__ == "__main__":
    main()
